const locales = { ro, en };
const LANG_KEY = 'cuib.lang';

function readLang() {
  try {
    const l = localStorage.getItem(LANG_KEY);
    return locales[l] ? l : 'ro';
  } catch {
    return 'ro';
  }
}

let current = readLang();

// Binding live: modulele importa `t` si vad limba activa (setata deja la init).
export let t = locales[current];

export function setLocale(code) {
  if (!locales[code]) return;
  current = code;
  t = locales[current];
  try { localStorage.setItem(LANG_KEY, code); } catch { /* stocare indisponibila */ }
}

export function currentLocale() {
  return current;
}

export function availableLocales() {
  return Object.keys(locales);
}
